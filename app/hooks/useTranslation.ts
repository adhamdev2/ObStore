export function useTranslation() {
    const { user } = useAuth();
    // Memoize so consumers only re-render when the language actually changes
    return useMemo(() => {
        const lang = user?.settings?.language === "ar" ? "ar" : "en";
        const isArabic = lang === "ar";
        return { t: dictionary[lang], isArabic, lang };
    }, [user?.settings?.language]);
}